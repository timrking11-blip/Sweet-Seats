"""Linear-triggered Perplexity research agent (SS-RESEARCH-0.1).

Flow: Linear webhook/poll -> permission gate -> Perplexity Agent API -> Linear comment.
Network clients are injected so tests run fully offline with synthetic fixtures.
"""
from __future__ import annotations

import hashlib
import hmac
import os
import time
from dataclasses import dataclass, field
from typing import Any, Callable, Protocol

LINEAR_GRAPHQL_URL = "https://api.linear.app/graphql"
RESEARCH_LABEL = "research"
DEEP_LABEL = "research:deep"
MAX_WEBHOOK_AGE_S = 60
# Topics the README forbids claiming or that need source-registry approval first.
BLOCKED_TERMS = ("guaranteed savings", "cheapest price", "auto-purchase", "unannounced")

ISSUE_QUERY = """query Issue($id: String!) { issue(id: $id) { id identifier title description url
  labels { nodes { name } } } }"""
COMMENT_MUTATION = """mutation C($input: CommentCreateInput!) { commentCreate(input: $input) {
  success comment { id url } } }"""


class GraphQL(Protocol):
    def __call__(self, query: str, variables: dict[str, Any]) -> dict[str, Any]: ...


class Researcher(Protocol):
    def __call__(self, prompt: str, preset: str) -> str: ...


@dataclass
class Decision:
    run: bool
    preset: str = "fast"
    reason: str = ""


@dataclass
class ResearchAgent:
    graphql: GraphQL
    researcher: Researcher
    seen: set[str] = field(default_factory=set)  # idempotency; replace with Postgres in Phase 2

    def gate(self, issue: dict[str, Any]) -> Decision:
        labels = {l["name"].lower() for l in issue["labels"]["nodes"]}
        if RESEARCH_LABEL not in labels and DEEP_LABEL not in labels:
            return Decision(False, reason="missing research label")
        text = f"{issue['title']} {issue.get('description') or ''}".lower()
        hit = next((t for t in BLOCKED_TERMS if t in text), None)
        if hit:
            return Decision(False, reason=f"blocked term: {hit}")
        return Decision(True, "medium" if DEEP_LABEL in labels else "fast")

    def handle(self, issue_id: str) -> dict[str, Any]:
        if issue_id in self.seen:
            return {"status": "duplicate"}
        issue = self.graphql(ISSUE_QUERY, {"id": issue_id})["issue"]
        decision = self.gate(issue)
        if not decision.run:
            return {"status": "skipped", "reason": decision.reason}
        report = self.researcher(build_prompt(issue), decision.preset)
        body = format_comment(report, decision.preset)
        out = self.graphql(COMMENT_MUTATION, {"input": {"issueId": issue["id"], "body": body}})
        self.seen.add(issue_id)
        return {"status": "posted", "preset": decision.preset, "comment": out["commentCreate"]["comment"]}


def build_prompt(issue: dict[str, Any]) -> str:
    return (
        f"Linear issue {issue['identifier']}: {issue['title']}\n\n"
        f"{issue.get('description') or 'No description.'}\n\n"
        "Return: Executive summary; Key findings; Options; Risks and unknowns; "
        "Recommended next actions; Sources (URLs). Separate facts from interpretation. "
        "Do not claim guaranteed savings, whole-market cheapest prices or unannounced access."
    )


def format_comment(report: str, preset: str) -> str:
    ts = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    return (f"## Research report ({preset})\n\nGenerated by Perplexity Agent API at {ts}.\n\n"
            f"{report}\n\n---\nHuman review required before implementation (SS-RESEARCH-0.1).")


def verify_linear_webhook(raw_body: bytes, signature: str | None, secret: str,
                          webhook_ts_ms: int | None, now: Callable[[], float] = time.time) -> bool:
    """Linear signs the raw body with HMAC-SHA256 (hex) in the `Linear-Signature` header."""
    if not signature or webhook_ts_ms is None:
        return False
    expected = hmac.new(secret.encode(), raw_body, hashlib.sha256).hexdigest()
    if not hmac.compare_digest(expected, signature):
        return False
    return abs(now() * 1000 - webhook_ts_ms) <= MAX_WEBHOOK_AGE_S * 1000


def should_trigger(event: dict[str, Any]) -> str | None:
    """Return an issue id if a webhook event should start research."""
    if event.get("type") != "Issue" or event.get("action") not in ("create", "update"):
        return None
    labels = {l.get("name", "").lower() for l in event.get("data", {}).get("labels", [])}
    if not labels & {RESEARCH_LABEL, DEEP_LABEL}:
        return None
    if event["action"] == "update" and "labelIds" not in event.get("updatedFrom", {}):
        return None  # only fire when labels changed, not on every edit
    return event["data"]["id"]


# ---- live adapters (not used in tests) ----
def live_graphql(query: str, variables: dict[str, Any]) -> dict[str, Any]:
    import httpx
    r = httpx.post(LINEAR_GRAPHQL_URL, timeout=30, json={"query": query, "variables": variables},
                   headers={"Authorization": os.environ["LINEAR_API_KEY"]})
    r.raise_for_status()
    p = r.json()
    if p.get("errors"):
        raise RuntimeError(p["errors"])
    return p["data"]


def live_researcher(prompt: str, preset: str) -> str:
    from perplexity import Perplexity
    resp = Perplexity().responses.create(preset=preset, input=prompt)
    return resp.output_text
