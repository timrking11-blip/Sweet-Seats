"""Worker: drain research jobs, run Perplexity, write the report back to Linear.

Queue is abstracted so the Phase 2 durable job/outbox (Postgres) can replace the in-memory one.
"""
from __future__ import annotations

import asyncio
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Protocol

from adapters.linear import LinearClient
from adapters.perplexity_research import build_prompt, preset_for_labels, run_research

MAX_CONCURRENT = 3  # deep research is compute-heavy; stay inside rate limits
REPORT_MARKER = "<!-- sweet-seats:research-report -->"


@dataclass
class ResearchJob:
    issue_id: str
    source: str  # "webhook" | "sweep"
    attempts: int = 0


class JobQueue(Protocol):
    async def enqueue(self, job: ResearchJob) -> bool: ...
    async def dequeue(self) -> ResearchJob | None: ...


@dataclass
class InMemoryQueue:
    """Dev/test only. Dedupes by issue_id while pending."""
    _items: list[ResearchJob] = field(default_factory=list)

    async def enqueue(self, job: ResearchJob) -> bool:
        if any(j.issue_id == job.issue_id for j in self._items):
            return False
        self._items.append(job)
        return True

    async def dequeue(self) -> ResearchJob | None:
        return self._items.pop(0) if self._items else None


def format_report(report: str, preset: str) -> str:
    ts = datetime.now(timezone.utc).isoformat(timespec="seconds")
    return (f"{REPORT_MARKER}\n## Research report ({preset})\n\n"
            f"Generated by Perplexity Agent API on {ts}\n\n{report}\n\n"
            "Next step: human review required before implementation work begins.")


async def process_job(job: ResearchJob, linear: LinearClient, client_factory=None) -> str:
    issue = await linear.get_issue(job.issue_id)
    labels = [l["name"] for l in issue["labels"]["nodes"]]
    preset = preset_for_labels(labels)
    if preset is None:
        return "skipped"
    report = await run_research(build_prompt(issue), preset, client_factory)
    await linear.add_comment(issue["id"], format_report(report, preset))
    return "posted"


async def drain(queue: JobQueue, linear: LinearClient, client_factory=None) -> list[str]:
    sem = asyncio.Semaphore(MAX_CONCURRENT)
    tasks = []

    async def run(job):
        async with sem:
            try:
                return await process_job(job, linear, client_factory)
            except Exception as exc:  # surfaced to caller; retries belong to the durable queue
                return f"failed:{type(exc).__name__}"

    while (job := await queue.dequeue()) is not None:
        tasks.append(asyncio.create_task(run(job)))
    return list(await asyncio.gather(*tasks))


async def sweep(queue: JobQueue, linear: LinearClient, label: str = "research-quick") -> int:
    """Scheduled automation for simple research: enqueue open issues carrying the label.
    Production version must skip issues that already carry REPORT_MARKER (stored in research_jobs)."""
    count = 0
    for issue in await linear.open_issues_with_label(label):
        count += await queue.enqueue(ResearchJob(issue["id"], "sweep"))
    return count
